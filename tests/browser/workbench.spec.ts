import { expect, test } from '@playwright/test';

test.use({ viewport: { width: 1440, height: 1000 }, contextOptions: { reducedMotion: 'reduce' } });

test('nested tree keeps same-name files, closed content, rename validation and inline creation', async ({ page }) => {
  await page.goto('/preview?scene=unit');
  const tree = page.getByRole('tree', { name: '项目目录树' });
  await expect(tree.getByRole('treeitem', { name: 'parser.rs', exact: true })).toHaveCount(2);
  await tree.locator('[title="src/utils/parser.rs"]').click();
  const editor = page.getByLabel('编辑 parser.rs', { exact: true });
  await editor.fill('// source parser only\npub fn parse() {}');
  await tree.locator('[title="tests/parser.rs"]').click();
  await expect(editor).toHaveValue(/#\[test\]/);
  await expect(page.getByRole('tab', { name: /parser.rs/ })).toHaveCount(2);
  await page.getByRole('button', { name: '关闭 src/utils/parser.rs', exact: true }).click();
  await expect(tree.locator('[title="src/utils/parser.rs"]')).toBeVisible();
  await tree.locator('[title="src/utils/parser.rs"]').click();
  await expect(editor).toHaveValue('// source parser only\npub fn parse() {}');
  await tree.locator('[title="src/utils/parser.rs"]').press('F2');
  await page.getByRole('textbox', { name: '重命名', exact: true }).fill('mod.rs');
  await page.getByRole('textbox', { name: '重命名', exact: true }).press('Enter');
  await expect(page.getByText('此目录中已存在同名文件或文件夹', { exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: '重命名', exact: true }).fill('tokens.rs');
  await page.getByRole('textbox', { name: '重命名', exact: true }).press('Enter');
  await expect(page.getByLabel('编辑 tokens.rs', { exact: true })).toHaveValue('// source parser only\npub fn parse() {}');
  await page.getByRole('button', { name: '新建文件夹', exact: true }).click();
  await page.getByRole('textbox', { name: '文件夹名称', exact: true }).fill('nested');
  await page.getByRole('textbox', { name: '文件夹名称', exact: true }).press('Enter');
  await page.getByRole('button', { name: '新建文件', exact: true }).click();
  await page.getByRole('textbox', { name: '文件名称', exact: true }).fill('tokens.rs');
  await page.getByRole('textbox', { name: '文件名称', exact: true }).press('Enter');
  await expect(tree.locator('[title="src/utils/nested/tokens.rs"]')).toHaveAttribute('aria-level', '4');
  await expect(page.getByLabel('编辑 tokens.rs', { exact: true })).toHaveValue('fn main() {\n    \n}');
});

test('normal and fullscreen IDE preserve editor, terminal, quote and layout; Return and Escape collapse IDE', async ({ page }, info) => {
  await page.goto('/preview?scene=unit');
  await page.getByRole('button', { name: 'IDE 与终端', exact: true }).click();
  const ide = page.getByRole('region', { name: 'IDE 与终端', exact: true });
  const editor = page.getByLabel('编辑 move_demo.rs', { exact: true });
  const code = 'fn main() {\n    println!("layout kept");\n}';
  await editor.fill(code);
  await expect(ide.locator('[title^="rustc"]')).toBeVisible();
  await expect(ide.getByRole('button', { name: '运行', exact: true })).toHaveCount(0);
  const command = page.getByRole('textbox', { name: '终端命令' });
  await command.fill('rustc examples/move_demo.rs');
  await command.press('Enter');
  await expect(page.getByRole('log', { name: '终端输出' })).toContainText('layout kept');
  await page.getByRole('button', { name: '引用终端输出' }).click();
  const agent = page.getByRole('complementary', { name: 'Agent', exact: true });
  await expect(agent.getByRole('button', { name: '移除引用' })).toBeVisible();
  await expect(agent).toContainText('layout kept');
  await page.getByLabel('向 Agent 提问', { exact: true }).fill('保留工作台草稿');
  await command.fill('ls examples');
  const beforeResize = (await ide.boundingBox())!.height;
  await page.getByRole('separator', { name: '调整 IDE 高度' }).press('ArrowUp');
  await expect.poll(async () => (await ide.boundingBox())!.height).toBeGreaterThan(beforeResize + 5);
  const height = (await ide.boundingBox())!.height;
  await page.screenshot({ path: `.amp/in/artifacts/ide-normal-${info.project.name}.png`, animations: 'disabled' });
  await page.getByRole('button', { name: '全屏 IDE', exact: true }).click();
  await expect(editor).toHaveValue(code);
  await expect(command).toHaveValue('ls examples');
  await expect(page.getByLabel('向 Agent 提问', { exact: true })).toHaveValue('保留工作台草稿');
  await expect(page.getByRole('heading', { name: '所有权与借用', exact: true })).toHaveCount(0);
  expect((await ide.boundingBox())!.height).toBeGreaterThan(height * 1.5);
  await page.screenshot({ path: `.amp/in/artifacts/ide-fullscreen-${info.project.name}.png`, animations: 'disabled' });
  await page.getByRole('button', { name: '查看课件' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.screenshot({ path: `.amp/in/artifacts/lesson-drawer-${info.project.name}.png`, animations: 'disabled' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '返回学习', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '返回学习', exact: true }).click();
  await expect(page.getByRole('button', { name: 'IDE 与终端', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await expect(ide).toHaveCount(0);
  await page.getByRole('button', { name: 'IDE 与终端', exact: true }).click();
  await expect(editor).toHaveValue(code);
  await expect(command).toHaveValue('ls examples');
  await expect.poll(async () => (await ide.boundingBox())!.height).toBeCloseTo(height, 0);
  await page.getByRole('button', { name: '询问这个文件', exact: true }).click();
  await expect(agent).toContainText('examples/move_demo.rs');
  await expect(agent).toContainText('println!("layout kept")');
  await page.getByRole('button', { name: '全屏 IDE', exact: true }).click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'IDE 与终端', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await expect(ide).toHaveCount(0);
});

test('assessment keeps answers, offers advice quotes and records needs-work then passing retry', async ({ page }, info) => {
  await page.goto('/preview?scene=unit');
  await page.getByRole('button', { name: '开始单元测评' }).click();
  await page.getByLabel('你的回答', { exact: true }).fill('我还不明白变量为什么不能使用');
  await page.getByRole('button', { name: '返回单元（答案会保留）' }).click();
  await page.getByRole('button', { name: '继续测评', exact: true }).click();
  await expect(page.getByLabel('你的回答', { exact: true })).toHaveValue('我还不明白变量为什么不能使用');
  await page.getByRole('button', { name: '运行', exact: true }).click();
  await expect(page.getByText('error[E0382]: borrow of moved value: `name`', { exact: true })).toBeVisible();
  await page.screenshot({ path: `.amp/in/artifacts/assessment-${info.project.name}.png` });
  await page.getByRole('button', { name: '提交测评', exact: true }).click();
  await expect(page.getByText('这次还有需要修改的地方', { exact: true })).toBeVisible();
  await page.screenshot({ path: `.amp/in/artifacts/needs-work-${info.project.name}.png` });
  await page.getByRole('button', { name: '就此提问', exact: true }).first().click();
  const agent = page.getByRole('complementary', { name: 'Agent', exact: true });
  await expect(agent).toContainText('所有权与借用 · 测评');
  await expect(agent).toContainText('解释中没有说明所有权在哪一行、转移给了谁');
  await page.getByRole('button', { name: '重新测评', exact: true }).click();
  await expect(page.getByText('单元测评 · 第 2 次', { exact: true })).toBeVisible();
  await page.getByLabel('你的回答', { exact: true }).fill('let b = a 将所有权转移给 b，a 失效；用 clone 复制或借用 &a 保持 a 可用。');
  const editor = page.getByLabel('编辑 assessment_fix.rs', { exact: true });
  await editor.fill('fn shout(s: &String) -> String {\n    s.to_uppercase()\n}\n\nfn main() {\n    let name = String::from("ferris");\n    let loud = shout(&name);\n    println!("{} -> {}", name, loud);\n}');
  await page.getByRole('button', { name: '运行', exact: true }).click();
  await expect(page.getByText('ferris -> FERRIS', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '提交测评', exact: true }).click();
  await expect(page.getByText('本次测评通过', { exact: true })).toBeVisible();
  await page.screenshot({ path: `.amp/in/artifacts/passed-${info.project.name}.png` });
  await expect(page.getByText('本次做对的地方', { exact: true })).toBeHidden();
  await page.getByRole('button', { name: '补充反馈', exact: true }).click();
  await expect(page.getByText('本次做对的地方', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '补充反馈', exact: true }).locator('..').screenshot({ path: `.amp/in/artifacts/feedback-supplementary-${info.project.name}.png` });
  await page.getByRole('button', { name: '补充反馈', exact: true }).click();
  await page.getByRole('button', { name: '查看我的回答', exact: true }).click();
  await expect(page.getByText('let b = a 将所有权转移给 b，a 失效；用 clone 复制或借用 &a 保持 a 可用。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '返回单元', exact: true }).click();
  await page.getByText('测评记录', { exact: false }).click();
  await expect(page.getByRole('button', { name: /所有权与借用.*加强.*第 1 次/ })).toBeVisible();
  await expect(page.getByRole('button', { name: /所有权与借用.*通过.*第 2 次/ })).toBeVisible();
});

test('failed fixture lesson generation retains route and retries', async ({ page }, info) => {
  await page.goto('/preview?scene=route&fault=lesson');
  await page.locator('li').filter({ has: page.locator('[data-slot="card-title"]').filter({ hasText: '结构体与枚举' }) }).getByRole('button', { name: '进入', exact: true }).click();
  await expect(page.getByText('课件生成失败', { exact: true })).toBeVisible();
  await page.screenshot({ path: `.amp/in/artifacts/lesson-failure-${info.project.name}.png` });
  await page.getByRole('button', { name: '重新生成', exact: true }).click();
  await expect(page.getByText('课件生成失败', { exact: true })).toHaveCount(0);
  await expect(page.locator('.lesson-prose > p').first()).toBeVisible();
  await expect(page.getByRole('treeitem', { name: 'parser.rs', exact: true })).toHaveCount(2);
});
