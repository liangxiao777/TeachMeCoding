import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test, type Page, type TestInfo } from '@playwright/test';
import type { seedWorkspaces } from '../seed-workspaces';

test.use({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
const seed = (info: TestInfo) => JSON.parse(readFileSync(`.amp/in/browser-${info.project.name}.json`, 'utf8')) as ReturnType<typeof seedWorkspaces>;
const shot = (page: Page, info: TestInfo, name: string) => page.screenshot({ path: `.amp/in/artifacts/persistent-${name}-${info.project.name}.png` });
const visible = (page: Page, label: string) => page.getByRole('textbox', { name: label, exact: true }).filter({ visible: true });

test('new spaces, requirements, session drafts and message retries persist without fixture fallback', async ({ page }, info) => {
  await page.goto('/');
  const goal = `学习持久化 ${info.project.name}`;
  await visible(page, '学习目标').fill(goal);
  let dropped = false;
  await page.route('**/api/spaces', async (route) => {
    if (route.request().method() === 'POST' && !dropped) { dropped = true; await route.fetch(); await route.abort(); } else await route.continue();
  });
  await page.getByRole('button', { name: '创建学习空间' }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(visible(page, '学习目标')).toHaveValue(goal);
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await expect(page.getByRole('heading', { name: '从你的目标开始' })).toBeVisible();
  const url = page.url();
  await visible(page, '已有基础').fill('Python 基础，尚未学习 Rust');
  await page.getByRole('button', { name: '确认需求', exact: true }).click();
  await expect(page.getByText('需求已确认并保存', { exact: true })).toBeVisible();
  await visible(page, '会话草稿').fill('独立保存的需求问题');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await expect(page.getByText('草稿已保存', { exact: true })).toBeVisible();
  await shot(page, info, 'requirements');
  await page.reload();
  await expect(visible(page, '已有基础')).toHaveValue('Python 基础，尚未学习 Rust');
  await expect(visible(page, '会话草稿')).toHaveValue('独立保存的需求问题');
  let messageDropped = false;
  await page.route('**/sessions/*/messages', async (route) => {
    if (!messageDropped) { messageDropped = true; await route.fetch(); await route.abort(); } else await route.continue();
  });
  await page.getByRole('button', { name: '保存问题', exact: true }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(visible(page, '会话草稿')).toHaveValue('独立保存的需求问题');
  await visible(page, '会话草稿').fill('重试期间的新草稿');
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await expect(page.getByRole('article').filter({ hasText: '独立保存的需求问题' })).toHaveCount(1);
  await expect(visible(page, '会话草稿')).toHaveValue('重试期间的新草稿');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await expect(page.getByText('草稿已保存', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '学习路线', exact: true }).click();
  await expect(page.getByRole('heading', { name: '学习路线', exact: true, level: 1 })).toBeVisible();
  await expect(visible(page, '会话草稿')).toHaveValue('');
  await page.getByRole('button', { name: '全部空间', exact: true }).click();
  await expect(page.getByRole('heading', { name: goal, exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: /另一个 Python 空间/ }).click();
  await expect(visible(page, '会话草稿')).toHaveValue('');
  await page.goto(url);
  await expect(page.getByRole('article').filter({ hasText: '独立保存的需求问题' })).toHaveCount(1);
});

