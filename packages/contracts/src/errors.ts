/** Only explicitly declared, public scalar data may cross the current-notice boundary.
 * Titles/provider names are opaque display text; never put causes, credentials,
 * stacks, provider responses or instructions in these fields.
 */
export interface BusinessErrorParams {
  UNIT_LOCKED: { title: string };
  ACTIVE_UNIT_REMOVAL: { title: string };
  ACTIVE_UNIT_GOALS_CHANGED: { title: string };
  MODEL_OAUTH_REAUTH_REQUIRED: { provider: string };
  MODEL_OAUTH_REFRESH_FAILED: { provider: string };
  SEARCH_CODEX_LOGIN_REQUIRED: { provider: string };
  SEARCH_AUTH_FAILED: { provider: string };
  SEARCH_RATE_LIMITED: { provider: string };
  SEARCH_PROVIDER_UNAVAILABLE: { provider: string };
  WEB_FETCH_HTTP_FAILED: { status: number };
}
export type BusinessErrorDetail = {
  [Code in BusinessErrorCode]: Code extends keyof BusinessErrorParams
    ? { code: Code; params: BusinessErrorParams[Code] }
    : { code: Code; params?: never }
}[BusinessErrorCode];

/** Unknown runtime codes remain semantic failures; consumers must not fall back to raw text. */
export interface BusinessErrorResponse {
  code: string;
  params?: Record<string, string | number | boolean | null>;
}

/** Deliberately projects only public metadata, never properties of an Error/cause. */
export function businessErrorResponse(detail: BusinessErrorDetail): BusinessErrorResponse {
  let params: BusinessErrorResponse['params'];
  switch (detail.code) {
    case 'WEB_FETCH_HTTP_FAILED':
      if (Number.isInteger(detail.params?.status) && detail.params.status >= 100 && detail.params.status <= 599) params = { status: detail.params.status };
      break;
    case 'UNIT_LOCKED':
    case 'ACTIVE_UNIT_REMOVAL':
    case 'ACTIVE_UNIT_GOALS_CHANGED':
      if (typeof detail.params?.title === 'string') params = { title: detail.params.title };
      break;
    case 'MODEL_OAUTH_REAUTH_REQUIRED':
    case 'MODEL_OAUTH_REFRESH_FAILED':
    case 'SEARCH_CODEX_LOGIN_REQUIRED':
    case 'SEARCH_AUTH_FAILED':
    case 'SEARCH_RATE_LIMITED':
    case 'SEARCH_PROVIDER_UNAVAILABLE':
      if (typeof detail.params?.provider === 'string') params = { provider: detail.params.provider };
      break;
  }
  return { code: detail.code, ...(params ? { params } : {}) };
}
